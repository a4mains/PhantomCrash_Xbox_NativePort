#!/usr/bin/env python3
"""Compile GLSL 450 world shaders into a prebuilt SPIR-V C++ header."""

from __future__ import annotations

import pathlib
import shutil
import subprocess
import tempfile


def compile_spv(glslang: str, source: pathlib.Path, out_path: pathlib.Path) -> bytes:
    subprocess.run(
        [glslang, "-V", "-S", source.suffix.lstrip("."), "-o", str(out_path), str(source)],
        check=True,
    )
    return out_path.read_bytes()


def format_u32_array(name: str, data: bytes) -> str:
    if len(data) % 4 != 0:
        raise RuntimeError(f"SPIR-V byte length must be a multiple of 4: {len(data)}")
    words = [int.from_bytes(data[i : i + 4], "little") for i in range(0, len(data), 4)]
    lines = [f"inline constexpr std::uint32_t {name}[] = {{"]
    for i in range(0, len(words), 8):
        chunk = ", ".join(f"0x{w:08x}u" for w in words[i : i + 8])
        lines.append(f"  {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    root = pathlib.Path(__file__).resolve().parents[1]
    glslang = shutil.which("glslangValidator")
    if not glslang:
        raise RuntimeError("glslangValidator not found in PATH")
    vert_src = root / "port" / "src" / "shaders" / "world.vert"
    frag_src = root / "port" / "src" / "shaders" / "world.frag"
    out_hdr = root / "port" / "src" / "desktop_world_shaders_spv.hpp"
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = pathlib.Path(tmp)
        vert_spv = compile_spv(glslang, vert_src, tmp_dir / "world.vert.spv")
        frag_spv = compile_spv(glslang, frag_src, tmp_dir / "world.frag.spv")
    text = f"""#pragma once
// Generated by tools/compile_gpu_shaders.py from port/src/shaders/world.{{vert,frag}}.
// Do not edit by hand.

#include <cstdint>

namespace phantomcrash {{

{format_u32_array("kWorldVertSpv", vert_spv)}

{format_u32_array("kWorldFragSpv", frag_spv)}

}} // namespace phantomcrash
"""
    out_hdr.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {out_hdr} (vert={len(vert_spv)}B frag={len(frag_spv)}B)")


if __name__ == "__main__":
    main()
