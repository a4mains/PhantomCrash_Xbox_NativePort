#!/usr/bin/env python3
"""Generate portable CP932 2-byte + Unicode NFKC lookup tables for POSIX builds."""

from __future__ import annotations

import pathlib
import unicodedata


def build_cp932_table() -> list[int]:
    entries: list[int] = []
    leads = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
    for lead in leads:
        for trail in range(0x40, 0xFD):
            try:
                ch = bytes([lead, trail]).decode("cp932", "strict")
            except UnicodeDecodeError:
                entries.append(0xFFFD)
                continue
            if len(ch) != 1 or ord(ch) > 0xFFFF:
                raise RuntimeError(f"Unexpected CP932 mapping for {lead:#x} {trail:#x}: {ch!r}")
            entries.append(ord(ch))
    return entries


def build_unicode_tables():
    nfkd_entries: list[tuple[int, int, int]] = []
    nfkd_pool: list[int] = []
    ccc_entries: list[tuple[int, int]] = []
    comp_entries: list[tuple[int, int]] = []

    for cp in range(0x110000):
        ch = chr(cp)
        comb = unicodedata.combining(ch)
        if comb:
            ccc_entries.append((cp, comb))
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        nfkd = unicodedata.normalize("NFKD", ch)
        if nfkd != ch:
            offset = len(nfkd_pool)
            nfkd_pool.extend(ord(x) for x in nfkd)
            nfkd_entries.append((cp, offset, len(nfkd)))
        decomp = unicodedata.decomposition(ch)
        if decomp and not decomp.startswith("<"):
            parts = [int(x, 16) for x in decomp.split()]
            if (
                len(parts) == 2
                and unicodedata.combining(chr(parts[0])) == 0
                and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == ch
            ):
                key = (parts[0] << 21) | parts[1]
                comp_entries.append((key, cp))

    comp_entries.sort()
    return nfkd_entries, nfkd_pool, ccc_entries, comp_entries


def format_rows(items: list[str], cols: int) -> str:
    lines = []
    for i in range(0, len(items), cols):
        lines.append("  " + ", ".join(items[i : i + cols]) + ",")
    return "\n".join(lines)


def main() -> None:
    root = pathlib.Path(__file__).resolve().parents[1]
    out_path = root / "port" / "src" / "extract" / "text_cp932_table.hpp"

    cp932 = build_cp932_table()
    nfkd_entries, nfkd_pool, ccc_entries, comp_entries = build_unicode_tables()

    text = f"""#pragma once
// Generated by tools/gen_cp932_table.py from Python cp932 & unicodedata ({unicodedata.unidata_version}).
// Do not edit by hand.

#include <array>
#include <cstdint>

namespace phantomcrash::extract::detail {{

struct NfkdEntry {{
  std::uint32_t cp;
  std::uint32_t offset;
  std::uint8_t length;
}};

struct CccEntry {{
  std::uint32_t cp;
  std::uint8_t ccc;
}};

struct CompEntry {{
  std::uint64_t key;
  std::uint32_t composed;
}};

inline constexpr std::array<std::uint16_t, {len(cp932)}> kCp932Pairs = {{{{
{format_rows([f"0x{v:04X}" for v in cp932], 12)}
}}}};

inline constexpr std::array<char32_t, {len(nfkd_pool)}> kNfkdPool = {{{{
{format_rows([f"0x{v:X}" for v in nfkd_pool], 12)}
}}}};

inline constexpr std::array<NfkdEntry, {len(nfkd_entries)}> kNfkdEntries = {{{{
{format_rows([f"{{{cp:#x}, {off}, {ln}}}" for cp, off, ln in nfkd_entries], 6)}
}}}};

inline constexpr std::array<CccEntry, {len(ccc_entries)}> kCccEntries = {{{{
{format_rows([f"{{{cp:#x}, {c}}}" for cp, c in ccc_entries], 8)}
}}}};

inline constexpr std::array<CompEntry, {len(comp_entries)}> kCompEntries = {{{{
{format_rows([f"{{{k}ULL, {cp:#x}}}" for k, cp in comp_entries], 6)}
}}}};

}} // namespace phantomcrash::extract::detail
"""
    out_path.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {out_path} ({len(cp932)} cp932 pairs, {len(nfkd_entries)} nfkd, {len(ccc_entries)} ccc, {len(comp_entries)} comp)")


if __name__ == "__main__":
    main()
